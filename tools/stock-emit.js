#!/usr/bin/env node
// Writes server/stock.js: every scene the app has ever SHIPPED as a first-visit library, so
// the gallery sync (server/gallery-sync.js) does not publish your untouched copy of them
// under your name. Every profile carries them -- auto-publishing all of your scenes would
// otherwise post the same fifteen cards once per user.
//
//   node tools/stock-emit.js          rewrite server/stock.js
//   node tools/stock-emit.js --check  exit 1 if it is stale (tools/stockprobe.js runs this)
//
// Sources: DEFAULT_LIBRARY in EVERY commit of src/persist-presets.js (a profile saved in
// August still holds August's library), plus the effect names, because before 2026-08-05 the
// first visit got one neutral scene per effect, named after it (perEffectPresets), and today's
// "Blank canvas" is one more of those. Only what the match compares is kept: name, effect,
// state, palette, filters, per layer.
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const zlib = require("node:zlib");
const { execFileSync } = require("node:child_process");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "server", "stock.js");
const FILE = "src/persist-presets.js";
const git = args => execFileSync("git", args, { cwd: ROOT, encoding: "utf8", maxBuffer: 1 << 28 });

function libraryIn(src) {
  const at = src.indexOf("const DEFAULT_LIBRARY = ");
  if (at < 0) return [];
  const i = at + "const DEFAULT_LIBRARY = ".length;
  let t = src.slice(i, src.indexOf("\n", i)).trim();
  if (t.endsWith(";")) t = t.slice(0, -1);
  try { const a = JSON.parse(t); return Array.isArray(a) ? a : []; } catch (e) { return []; }
}
const pick = x => x && typeof x === "object" ? x : undefined;
function trim(p) {
  const ex = pick(p.extra) || {};
  return {
    name: p.name, effect: p.effect, state: pick(p.state) || {},
    palette: ex.palette, filters: ex.filters,
    layers: (Array.isArray(p.layers) ? p.layers : []).map(L => ({
      effect: L.effect, state: pick(L.state) || {}, palette: L.palette, filters: L.filters })),
  };
}

const seen = new Set(), scenes = [];
const add = p => {
  if (!p || typeof p.name !== "string") return;
  const t = trim(p), k = JSON.stringify(t);
  if (!seen.has(k)) { seen.add(k); scenes.push(t); }
};
for (const sha of git(["log", "--format=%H", "--", FILE]).split("\n").filter(Boolean)) {
  let src;
  try { src = git(["show", sha + ":" + FILE]); } catch (e) { continue; }
  libraryIn(src).forEach(add);
}
libraryIn(fs.readFileSync(path.join(ROOT, FILE), "utf8")).forEach(add);   // the working tree too

// name -> effect id for the neutral one-per-effect scenes; "Blank canvas" is Plasma's.
const effects = { "Blank canvas": "plasma" };
const reg = fs.readFileSync(path.join(ROOT, "src", "effects-registry.js"), "utf8");
for (const m of reg.matchAll(/\{ id: "([a-z0-9]+)", name: "([^"]+)"/g)) effects[m[2]] = m[1];

const blob = zlib.deflateRawSync(Buffer.from(JSON.stringify(scenes)), { level: 9 }).toString("base64");
const body = "\"use strict\";\n"
  + "// GENERATED by tools/stock-emit.js -- do not edit. Every scene ever shipped as the first-visit\n"
  + "// library (" + scenes.length + " distinct, deflated JSON) and the effect names the old one-scene-per-effect\n"
  + "// library used. gallery-sync.js skips a scene that still matches one of them.\n"
  + "const zlib = require(\"node:zlib\");\n"
  + "const SCENES = " + JSON.stringify(blob) + ";\n"
  + "module.exports = {\n"
  + "  scenes: JSON.parse(zlib.inflateRawSync(Buffer.from(SCENES, \"base64\")).toString(\"utf8\")),\n"
  + "  effects: " + JSON.stringify(effects) + ",\n"
  + "};\n";

if (process.argv.includes("--check")) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (have !== body) { console.error("server/stock.js is stale: run node tools/stock-emit.js"); process.exit(1); }
  console.log("server/stock.js is current (" + scenes.length + " stock scenes, " + Object.keys(effects).length + " effect names)");
} else {
  fs.writeFileSync(OUT, body);
  console.log("wrote server/stock.js: " + scenes.length + " stock scenes, " + Object.keys(effects).length
    + " effect names, " + body.length + " bytes");
}
